export function SocialPlatformIcon({
  channel,
  className = 'w-4 h-4',
  size,
}: {
  channel: SocialChannel | string;
  className?: string;
  size?: number;
}) {
  switch (channel.toLowerCase()) {
    case 'instagram':
      return <InstagramIcon className={className} size={size} />;
    case 'tiktok':
      return <TikTokIcon className={className} size={size} />;
    case 'facebook':
      return <FacebookIcon className={className} size={size} />;
    case 'threads':
      return <ThreadsIcon className={className} size={size} />;
    case 'whatsapp':
      return <WhatsAppIcon className={className} size={size} />;
    default:
      return <InstagramIcon className={className} size={size} />;
  }
}
